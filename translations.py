def translate_label(label, lang):
    if lang == "en":
        return label
    if "___" in label:
        crop, disease = label.split("___", 1)
    else:
        crop, disease = label, ""

    crop_key = crop
    crop_text = LABELS.get(crop_key, {}).get(lang, crop.replace("_", " "))

    disease_text = disease.replace("_", " ")
    for key, values in DISEASE_LABELS.items():
        if disease in (key, key.rstrip("_")):
            disease_text = values.get(lang, values["en"])
            break

    return disease_text if not crop else f"{crop_text} — {disease_text}"

def translate_text(text, lang):
    if lang == "en":
        return text
    return GENERIC_TEXT.get(text, {}).get(lang, text)



def translate_information(information, language):

    # English needs no translation
    if language == "en":
        return information

    translated_information = information.copy()

    # Get selected language translations
    translations = DISEASE_INFORMATION_TRANSLATIONS.get(language, {})

    # Translate symptoms
    translated_information["symptoms"] = [
        translations.get(item, item)
        for item in information.get("symptoms", [])
    ]

    # Translate fertilizer guidance
    translated_information["fertilizer"] = [
        translations.get(item, item)
        for item in information.get("fertilizer", [])
    ]

    # Translate prevention advice
    translated_information["prevention"] = [
        translations.get(item, item)
        for item in information.get("prevention", [])
    ]

    # Translate crop and disease names
    translated_information["crop"] = LABELS.get(
        information.get("crop", ""),
        {}
    ).get(
        language,
        information.get("crop", "")
    )

    translated_information["disease"] = DISEASE_LABELS.get(
        information.get("disease", ""),
        {}
    ).get(
        language,
        information.get("disease", "")
    )

    return translated_information
